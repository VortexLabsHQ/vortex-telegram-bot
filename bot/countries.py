"""Country system for the Vortex Telegram Bot.

Country and language are SEPARATE settings (the user's decision):
  - Country drives the timezone, the local currency for prices, the
    capital city used for prayer times, and local content.
  - Language drives ONLY the bot's language (see bot/locale.py).

195 countries (193 UN members + the Holy See + Palestine).

The English country name is the KEY: the installer asks the user to
paste the English name from the README, and ``get_country`` matches it
case-insensitively and whitespace-tolerantly. Unknown names return
None (never raise).

The current country is resolved per call through a provider callable
(wired in main.py / handlers.py to ``Database.get_country``), so an
/admin change applies immediately. Without a provider the default
country ("United States") is used.
"""

