# AlAdhan calculation method per country (https://api.aladhan.com/v1).
# Only the methods this project is sure about are listed; everything
# else uses the API default (3 = Muslim World League). Iran keeps
# method 7 (Tehran), the value the bot has always used.
_PRAYER_METHODS: dict[str, int] = {
    "Iran": 7,  # Institute of Geophysics, University of Tehran
    "Saudi Arabia": 4,  # Umm al-Qura University, Makkah
    "Egypt": 5,  # Egyptian General Authority of Survey
    "Turkey": 13,  # Diyanet (Turkey)
    "Pakistan": 1,  # University of Islamic Sciences, Karachi
    "United States": 2,  # Islamic Society of North America
    "United Kingdom": 2,  # Islamic Society of North America
}
PRAYER_METHOD_DEFAULT = 3  # Muslim World League


def _norm_name(name: str | None) -> str:
    """Case-insensitive, whitespace-tolerant key for country names."""
    if not name:
        return ""
    return " ".join(str(name).strip().lower().split())


def get_country(name: str | None) -> Country | None:
    """Look up a country by its English name (case/whitespace
    insensitive). Returns None when unknown — never raises."""
    if not name:
        return None
    wanted = _norm_name(name)
    for country in _COUNTRY_ROWS:
        if _norm_name(country.name) == wanted:
            return country
    return None


def list_country_names() -> list[str]:
    """All supported country names (English), sorted alphabetically."""
    return sorted(COUNTRIES)


def list_languages() -> list[str]:
    """All supported language codes, sorted alphabetically."""
    return sorted(LANGUAGES)


def prayer_method(country_name: str | None) -> int:
    """AlAdhan calculation-method id for a country (default 3)."""
    country = get_country(country_name)
    if country is None:
        return PRAYER_METHOD_DEFAULT
    return _PRAYER_METHODS.get(country.name, PRAYER_METHOD_DEFAULT)


# ----------------------------------------------------------------------
# Current-country provider (wired to the DB at startup).
# ----------------------------------------------------------------------

_country_provider = None  # type: ignore[assignment]


def set_country_provider(fn) -> None:
    """Register a zero-arg callable returning the current country name
    (English). Called once at startup from main.py / handlers.py with
    ``Database.get_country``; before that the default country applies."""
    global _country_provider
    _country_provider = fn


def current_country_name() -> str:
    """The bot's current country (English name)."""
    try:
        if _country_provider is not None:
            name = _country_provider()
            if get_country(name) is not None:
                return get_country(name).name  # type: ignore[union-attr]
    except Exception:
        pass
    return DEFAULT_COUNTRY


def current_country() -> Country:
    """The bot's current country entry (never None)."""
    country = get_country(current_country_name())
    return country if country is not None else COUNTRIES[DEFAULT_COUNTRY]


def country_timezone(country_name: str | None = None) -> ZoneInfo:
    """ZoneInfo for a country (or the current country when omitted).
    Falls back to UTC when the zone is unknown."""
    country = get_country(country_name) if country_name else current_country()
    tz_name = country.timezone if country else "UTC"
    try:
        return ZoneInfo(tz_name)
    except Exception:
        return ZoneInfo("UTC")


def country_now(country_name: str | None = None) -> datetime:
    """Current local time in a country (or the current country)."""
    return datetime.now(country_timezone(country_name))


def country_today(country_name: str | None = None) -> str:
    """Current local date ('YYYY-MM-DD') in a country (or the current
    country). Used as the daily-quota day, so the quota resets at
    local midnight, not UTC midnight."""
    return country_now(country_name).strftime("%Y-%m-%d")


def currency_code(country_name: str | None = None) -> str:
    """ISO currency code for a country (or the current country)."""
    country = get_country(country_name) if country_name else current_country()
    return country.currency if country else "USD"
